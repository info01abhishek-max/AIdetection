export function validateAudioFile(file: File): { valid: boolean; error?: string } {
  const supportedTypes = [
    'audio/wav', 'audio/wave', 'audio/x-wav',
    'audio/mpeg', 'audio/mp3',
    'audio/mp4', 'audio/m4a',
    'audio/flac', 'audio/x-flac',
    'audio/ogg', 'audio/vorbis', 'audio/opus',
    'audio/webm'
  ]

  const supportedExtensions = ['.wav', '.mp3', '.m4a', '.flac', '.ogg', '.opus', '.webm']
  const ext = file.name.toLowerCase().substring(file.name.lastIndexOf('.'))

  if (!supportedTypes.includes(file.type) && !supportedExtensions.includes(ext)) {
    return { valid: false, error: `Unsupported format. Supported: WAV, MP3, M4A, FLAC, OGG, OPUS, WebM` }
  }

  const maxSize = 100 * 1024 * 1024 // 100MB
  if (file.size > maxSize) {
    return { valid: false, error: `File too large. Maximum size: 100MB` }
  }

  if (file.size === 0) {
    return { valid: false, error: 'Empty file' }
  }

  return { valid: true }
}

export async function createAudioPreview(file: File): Promise<string> {
  return URL.createObjectURL(file)
}

export async function extractAudioMetadata(file: File): Promise<AudioMetadata> {
  return new Promise((resolve, reject) => {
    const audio = new Audio()
    const url = URL.createObjectURL(file)

    audio.addEventListener('loadedmetadata', () => {
      URL.revokeObjectURL(url)
      resolve({
        duration: audio.duration,
        sampleRate: 0, // Not available from browser Audio API
        channels: 0,   // Not available from browser Audio API
        format: file.type || 'unknown',
        size: file.size,
      })
    })

    audio.addEventListener('error', () => {
      URL.revokeObjectURL(url)
      reject(new Error('Failed to load audio metadata'))
    })

    audio.src = url
    audio.load()
  })
}

